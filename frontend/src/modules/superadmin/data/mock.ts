import type { AuditLog, Company } from '../types';
import { getPlan } from './catalog';
import { generateActivationKey, generateLoginEmail } from '../utils/activationKey';

function companyFromPlan(
  base: Omit<Company, 'features' | 'quotas'> & { planId: string; features?: Company['features']; quotas?: Company['quotas'] }
): Company {
  const plan = getPlan(base.planId)!;
  const userCount = base.quotas?.telecallers || base.quotas?.seats || 10;
  const planTag = base.planId?.includes('ivr') || base.features?.some((f) => f.startsWith('ivr_')) ? 'IVR' : 'CRM';
  const codeDigits = base.code.replace('BN-', '');
  return {
    ...base,
    loginEmail: base.loginEmail || generateLoginEmail(base.contactName, base.name, codeDigits),
    adminPassword: base.adminPassword || `BNOrbit@${base.code.replace('BN-', '')}#2026`,
    activationKey: base.activationKey || generateActivationKey(base.name, planTag, base.endDate),
    pricePerUser: base.pricePerUser || 2000,
    totalMonthlyBilling: base.totalMonthlyBilling || userCount * 2000,
    paymentStatus: base.paymentStatus || 'internal',
    features: base.features ?? plan.features,
    quotas: base.quotas ?? plan.quotas,
  };
}

